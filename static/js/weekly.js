/**
 * weekly.js - "This week's curated picks" panel (lives on the Discover page)
 */

let _weeklyLoaded = false;

/** Expand/collapse the "This week's curated picks" panel on the Discover page (lazy-loads once). */
function toggleWeeklyPanel(header) {
    const panel = header.closest('.weekly-panel');
    if (!panel) return;
    panel.classList.toggle('collapsed');
    if (!panel.classList.contains('collapsed') && !_weeklyLoaded) {
        loadWeekly();
    }
}

/** Programmatically open the weekly panel (used when Discover has nothing to show). */
function expandWeeklyPanel() {
    const panel = document.getElementById('weeklyPanel');
    if (panel && panel.classList.contains('collapsed')) {
        panel.classList.remove('collapsed');
        if (!_weeklyLoaded) loadWeekly();
    }
}

async function loadWeekly() {
    const container = document.getElementById('weeklyPicks');
    if (!container) return;
    container.innerHTML = '<div class="loading-msg">Curating this week\'s picks...</div>';
    try {
        const res = await fetch('/api/weekly-discovery');
        const data = await res.json();
        _weeklyLoaded = true;
        renderWeekly(data);
    } catch (err) {
        console.error('Weekly load error:', err);
        renderErrorView(container, 'Failed to load weekly picks', loadWeekly);
    }
}

async function refreshWeeklyDiscovery() {
    if (window.STATIC_MODE) {
        showToast('📄 Read-only snapshot — picks are fixed until the next rebuild');
        return;
    }
    document.getElementById('weeklyPicks').innerHTML = '<div class="loading-msg">Refreshing picks...</div>';
    await loadWeekly();
    showToast('✨ Weekly picks refreshed!');
}

function renderWeekly(data) {
    const msg = document.getElementById('weeklyMessage');
    if (msg) msg.textContent = data.message || '';

    const container = document.getElementById('weeklyPicks');
    if (!data.picks || data.picks.length === 0) {
        container.innerHTML = '<div class="loading-msg">No picks this week. Check back soon!</div>';
        return;
    }

    let html = '';
    data.picks.forEach((pick, i) => {
        const extraHtml = `
            <div class="wp-number">#${i + 1}</div>
            ${pick.why_you ? `<div class="wp-why-you">${escapeHtml(pick.why_you)}</div>` : ''}
        `;
        html += songCard({
            artist: pick.artist,
            song: pick.song,
            year: pick.year || null,
            reason: pick.reason,
            listened: pick.listened,
            source: 'weekly',
            cardClass: 'weekly-pick',
            extraHtml: extraHtml,
        });
    });

    container.innerHTML = html;
}

function exportWeeklyPlaylist() {
    const picks = document.querySelectorAll('.weekly-pick');
    if (!picks.length) {
        showToast('No picks to export');
        return;
    }

    let text = 'Weekly Discovery Playlist\n';
    text += '='.repeat(40) + '\n\n';
    
    picks.forEach((pick, i) => {
        const artist = pick.querySelector('.song-artist')?.textContent || '';
        const song = pick.querySelector('.song-title')?.textContent?.replace(/[""""]/g, '') || '';
        const searchUrl = `https://open.spotify.com/search/${encodeURIComponent(artist + ' ' + song)}`;
        text += `${i + 1}. ${artist} – ${song}\n   ${searchUrl}\n`;
    });

    text += '\n---\nGenerated by TasteScope';

    // Offer both copy and download
    const blob = new Blob([text], { type: 'text/plain' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = 'weekly-discovery-playlist.txt';
    a.click();
    URL.revokeObjectURL(a.href);
    
    navigator.clipboard.writeText(text).then(() => {
        showToast('Playlist copied & downloaded! Each song has a Spotify search link.');
    }).catch(() => {
        showToast('Playlist downloaded! Each song has a Spotify search link.');
    });
}
