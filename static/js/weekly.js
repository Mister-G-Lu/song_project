/**
 * weekly.js - Weekly discovery picks view
 */

async function loadWeekly() {
    showViewLoading('view-weekly', '✨ Curating your weekly picks...');
    try {
        const res = await fetch('/api/weekly-discovery');
        const data = await res.json();
        hideViewLoading('view-weekly');
        renderWeekly(data);
    } catch (err) {
        hideViewLoading('view-weekly');
        console.error('Weekly load error:', err);
        renderErrorView(document.getElementById('weeklyPicks'), 'Failed to load weekly picks', loadWeekly);
    }
}

async function refreshWeeklyDiscovery() {
    if (window.STATIC_MODE) {
        showToast('📄 Read-only snapshot — picks are fixed until the next rebuild');
        return;
    }
    document.getElementById('weeklyPicks').innerHTML = '<div class="loading-msg">Refreshing picks...</div>';
    await loadWeekly();
    showToast('✨ Weekly picks refreshed!');
}

function renderWeekly(data) {
    // Stats banner
    const statsHtml = `
        <div class="weekly-stat">
            <div class="ws-value">${data.stats?.total_songs_rated || 'N/A'}</div>
            <div class="ws-label">Total Rated</div>
        </div>
        <div class="weekly-stat">
            <div class="ws-value">${data.stats?.unique_artists || 'N/A'}</div>
            <div class="ws-label">Unique Artists</div>
        </div>
        <div class="weekly-stat">
            <div class="ws-value">${data.stats?.recent_avg || 'N/A'}</div>
            <div class="ws-label">This Month Avg</div>
        </div>
    `;
    document.getElementById('weeklyStats').innerHTML = statsHtml;

    // Add message below stats
    const banner = document.getElementById('weeklyBanner');
    const existingMsg = banner.querySelector('.weekly-message');
    if (existingMsg) existingMsg.remove();
    const msgDiv = document.createElement('div');
    msgDiv.className = 'weekly-message';
    msgDiv.textContent = data.message || '';
    banner.appendChild(msgDiv);

    // Picks
    const container = document.getElementById('weeklyPicks');
    if (!data.picks || data.picks.length === 0) {
        container.innerHTML = '<div class="loading-msg">No picks this week. Check back soon!</div>';
        return;
    }

    let html = '';
    data.picks.forEach((pick, i) => {
        const artist_esc = escapeHtml(pick.artist);
        const song_esc = escapeHtml(pick.song);
        // escapeJsAttr: safe for single-quoted JS strings inside onclick
        // (escapeHtml's &#039; would be decoded back to ' and break the JS).
        const artist_js = escapeJsAttr(pick.artist);
        const song_js = escapeJsAttr(pick.song);
        html += `<div class="weekly-pick">
            <div class="wp-number">#${i + 1}</div>
            <div class="wp-artist">${artist_esc}</div>
            <div class="wp-song">“${song_esc}”</div>
            <div class="wp-reason">${escapeHtml(pick.reason)}</div>
            ${pick.why_you ? `<div class="wp-why-you">${escapeHtml(pick.why_you)}</div>` : ''}
            <div class="wp-actions">
                <button class="rec-btn rec-btn-listen" onclick="searchSpotifyTrack('${artist_js}', '${song_js}')" title="Open on Spotify">&#9654; Listen</button>
                ${listenedButtonHtml(pick.artist, pick.song, pick.listened)}
                ${ignoreButtonHtml(pick.artist, pick.song)}
                <button class="rec-btn rec-btn-add" onclick="quickAddFromRecommender('${artist_js}', '${song_js}', 'weekly')">+ Save with Rating</button>
            </div>
        </div>`;
    });

    container.innerHTML = html;
}

function exportWeeklyPlaylist() {
    const picks = document.querySelectorAll('.weekly-pick');
    if (!picks.length) {
        showToast('No picks to export');
        return;
    }

    let text = 'Weekly Discovery Playlist\n';
    text += '='.repeat(40) + '\n\n';
    
    picks.forEach((pick, i) => {
        const artist = pick.querySelector('.wp-artist')?.textContent || '';
        const song = pick.querySelector('.wp-song')?.textContent?.replace(/["“”]/g, '') || '';
        const searchUrl = `https://open.spotify.com/search/${encodeURIComponent(artist + ' ' + song)}`;
        text += `${i + 1}. ${artist} – ${song}\n   ${searchUrl}\n`;
    });

    text += '\n---\nGenerated by TasteScope';

    // Offer both copy and download
    const blob = new Blob([text], { type: 'text/plain' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = 'weekly-discovery-playlist.txt';
    a.click();
    URL.revokeObjectURL(a.href);
    
    navigator.clipboard.writeText(text).then(() => {
        showToast('Playlist copied & downloaded! Each song has a Spotify search link.');
    }).catch(() => {
        showToast('Playlist downloaded! Each song has a Spotify search link.');
    });
}
